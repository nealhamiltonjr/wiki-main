// ---------------------------------------------------------------------------
// Groups - the SOLE permission-granting mechanism (brief §3.8 / §3.18: an earlier
// individual page_permissions table was dropped in favor of groups-only, precisely
// to avoid two overlapping grant paths with no stated precedence).
// ---------------------------------------------------------------------------
export const groups = sqliteTable("groups", {
  id: id(),
  name: text("name").notNull().unique(),
  /** JSON string[] — the union of all group capabilities defines what members can do system-wide. */
  capabilities: text("capabilities", { mode: "json" }).$type<string[]>().default([]).notNull(),
  ...timestamps,
});

// Missing from the reviewed handoff despite being in its own design doc - added here.
