// ---------------------------------------------------------------------------
// Tokens - brief §3.10. Unified share-link + API token engine. scope_id is a
// BRANCH id (not a bare page id) when scope_type='branch' - a page can have
// multiple placements, each with its own security context (§3.1's fix again).
// ---------------------------------------------------------------------------
export const tokens = sqliteTable("tokens", {
  id: id(),
  type: text("type", { enum: ["share_link", "api_token"] }).notNull(),
  tokenHash: text("token_hash").notNull().unique(), // SHA-256; raw value shown once, never stored
  createdBy: text("created_by").notNull().references(() => users.id),
  name: text("name"),
  scopeType: text("scope_type", { enum: ["branch", "space", "account"] }).notNull(),
  scopeId: text("scope_id"), // branch id, space id, or null for account scope
  permission: text("permission", { enum: ["view", "edit", "admin"] }).notNull(),
  passwordHash: text("password_hash"), // optional, for password-protected share links
  expiresAt: integer("expires_at", { mode: "timestamp_ms" }),
  revokedAt: integer("revoked_at", { mode: "timestamp_ms" }),
  lastAccessedAt: integer("last_accessed_at", { mode: "timestamp_ms" }),
  warningCount: integer("warning_count").notNull().default(0),
  lastWarningAt: integer("last_warning_at", { mode: "timestamp_ms" }),
  ...timestamps,
});

